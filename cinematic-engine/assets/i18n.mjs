const STORAGE_KEY = "semeai_cinematic_language";

export function createI18n(root = document) {
  const supported = new Set(Object.keys(COPY));
  let language = "en";

  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    const browser = String(navigator.language || "en").toLowerCase().split("-")[0];
    language = supported.has(saved) ? saved : supported.has(browser) ? browser : "en";
  } catch {
    language = "en";
  }

  function text(key) {
    return COPY[language]?.[key] ?? COPY.en[key] ?? key;
  }

  function apply() {
    document.documentElement.lang = language;
    root.querySelectorAll("[data-copy]").forEach((node) => {
      node.textContent = text(node.dataset.copy);
    });
    root.querySelectorAll("[data-lang]").forEach((button) => {
      button.setAttribute("aria-pressed", String(button.dataset.lang === language));
    });
    window.dispatchEvent(new CustomEvent("cinematic:language", { detail: { language } }));
  }

  function setLanguage(next) {
    if (!supported.has(next) || next === language) return;
    language = next;
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // Language still changes when storage is unavailable.
    }
    apply();
  }

  root.querySelectorAll("[data-lang]").forEach((button) => {
    button.addEventListener("click", () => setLanguage(button.dataset.lang));
  });

  apply();
  return { apply, setLanguage, text, get language() { return language; } };
}
