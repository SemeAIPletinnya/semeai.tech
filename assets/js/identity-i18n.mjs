export function language() {
  const value = window.SemeAI_I18n?.lang || document.documentElement.lang || "en";
  return value === "uk" || value === "ru" ? value : "en";
}

export function t(key) {
  return copy[language()]?.[key] || copy.en[key] || key;
}

export function applyIdentityCopy(root = document) {
  root.querySelectorAll("[data-identity-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.identityI18n);
  });
  root.querySelectorAll("[data-identity-i18n-placeholder]").forEach((node) => {
    node.setAttribute("placeholder", t(node.dataset.identityI18nPlaceholder));
  });
}

window.addEventListener("semeai:lang", () => applyIdentityCopy());
